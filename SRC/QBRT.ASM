; QBRT.ASM - QuickLibrary runtime for RLINK qlb output
; (dispatcher behind b_ULVars[0])
; Source of the QB_RT table in RLOQBE.PAS.
; Rebuild: nasm -f bin QBRT.ASM -o QBRT.BIN
; (the bytes of QBRT.BIN are the QB_RT table; hash table and
; names are appended by RLINK).
; Assemble with NASM 0.98.39 (BIN\NASM.EXE): it does not
; shorten immediates (or bx,3 is 4 bytes), a newer NASM gives
; a smaller, different image and the offsets QB_RT_SIZE and
; QB_RT_STUB of RLOQBE.PAS would change.
; QB jumps here (far jmp) with CX = selector (CH = 0),
; DS = QB data segment.
; Selectors >= 8 are called with one word of arguments and
; need RETF 2.
; 0Ah (find procedure) and 10h (find common) are handled
; here, the rest is forwarded to /entry: Pascal style far
; call, selector is a word parameter on the stack (the
; procedure ends with RETF 2) and it is passed in CX too.
; Procedure names are found through a hash table (htab)
; generated by the linker:
;   slot  = { check word (hash OR 8000h, 0 = empty), offset
;             of the name entry in this segment }
;   entry = { offset, segment (relocated by the loader),
;             upper-case name, 0 }
;   The linker appends slots (htmask + 1 of them), then the
;   entries, after the code.
;   hash = h * 33 + c over the upper-cased name, h starts at
;   1505h (16 bit)
        bits 16
        cpu 8086
        org 0

; +0  far address of /entry (patched by linker)
ep:     dd      0
; +4  slots - 1 (patched by linker)
htmask: dw      0

disp:
        cmp     cl, 0Ah                 ; +6  dispatcher entry
        je      getproc
        cmp     cl, 10h
        je      getcommon
        push    cx                      ; keep the selector
; parameter of /entry (Pascal style: the procedure removes it)
        push    cx
        call    far [cs:ep]
        pop     cx
        cmp     cl, 8
        jb      .r0
        retf    2
.r0:    retf

; for b_ULVars[1] and b_ULVars[2]
stub:   retf

getcommon:
        xor     ax, ax
        xor     bx, bx
        xor     dx, dx
        retf    2

getproc:
        push    bp
        mov     bp, sp
        push    si
        push    di
        push    es
        push    ax                      ; [bp-8]  check word
        push    ax                      ; [bp-10] slot offset
        cld
; near pointer to string descriptor {len, ptr}
        mov     bx, [bp+6]
        mov     cx, [bx]
        mov     si, [bx+2]
        or      dx, dx
        jz      .f0
; DL = 1 (CDECL): look for '_' + name, convert '.' to '_'
        mov     dl, 1
.f0:    xor     dh, dh
; names and hash table are in this segment
        push    cs
        pop     es
        push    cx
        push    si
        mov     ax, 1505h
        or      dl, dl
        jz      .h1
        mov     ax, 0B604h
.h1:    jcxz    .h9
        mov     di, ax
        lodsb
        call    xform
        xor     ah, ah
        mov     bx, ax
        mov     ax, di
        shl     ax, 1
        shl     ax, 1
        shl     ax, 1
        shl     ax, 1
        shl     ax, 1
        add     ax, di
        add     ax, bx
        dec     cx
        jmp     short .h1
.h9:    pop     si
        pop     cx
        mov     di, ax
        or      ax, 8000h
        mov     [bp-8], ax
        mov     bx, [cs:htmask]
        and     di, bx
        shl     di, 1
        shl     di, 1
        mov     [bp-10], di
.probe: mov     di, [bp-10]
        mov     ax, [cs:di+htab]
        or      ax, ax
        jz      .none
        cmp     ax, [bp-8]
        jne     .nextslot
; offset of the entry {offset, segment, name} in this segment
        mov     bx, [cs:di+htab+2]
        lea     di, [bx+4]              ; its name (upper-case)
        or      dl, dl
        jz      .np
        cmp     byte [es:di], '_'
        jne     .nextslot
        inc     di
.np:    push    cx
        push    si
.cmp:   jcxz    .tail
        lodsb
        call    xform
        scasb
        jne     .miss
        dec     cx
        jmp     short .cmp
.tail:  cmp     byte [es:di], 0
.miss:  pop     si
        pop     cx
        jne     .nextslot
        mov     ax, [es:bx]
        mov     dx, [es:bx+2]
        jmp     short .done
.nextslot:
        mov     bx, [cs:htmask]
        shl     bx, 1
        shl     bx, 1
        or      bx, 3
        mov     di, [bp-10]
        add     di, 4
        and     di, bx
        mov     [bp-10], di
        jmp     short .probe
.none:  xor     ax, ax
        xor     dx, dx
.done:  add     sp, 4
        push    ax
        push    dx
        mov     ax, [0C2h]
        or      ax, [0C4h]
        jz      .nogw
        mov     bx, [bp+6]
        mov     di, 26
        call    far [0C2h]
.nogw:  pop     dx
        pop     ax
        pop     es
        pop     di
        pop     si
        pop     bp
        retf    2

xform:  or      dl, dl
        jz      .nodot
        cmp     al, '.'
        jne     .nodot
        mov     al, '_'
.nodot: cmp     al, 'a'
        jb      .ok
        cmp     al, 'z'
        ja      .ok
        sub     al, 20h
.ok:    ret


